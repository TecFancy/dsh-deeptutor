#!/usr/bin/env node
/**
 * Boot-verify dsh-deeptutor against the `dsh` on PATH.
 *
 * Why this exists: the manifest no longer caps the supported dsh line (that is
 * what issue #5 was about), so the compatibility gate is replaced by this
 * probe. The scheduled `dsh-compat` workflow runs it against the npm `latest`
 * and `next` releases; run it by hand after a dsh upgrade as well.
 *
 * What it does, against a throwaway DSH_HOME:
 *   1. packs this repository (prepack builds + typechecks) unless --spec is given;
 *   2. installs the package into a fresh `compat` profile;
 *   3. cold-boots that profile with a dead model endpoint;
 *   4. asserts the plugin activated (no `did not activate` / import failure).
 *
 * Usage:
 *   node scripts/check-dsh-compat.mjs [--spec <dir|tarball|npm-spec>] [--timeout 60]
 *                                     [--dsh-bin dsh] [--json] [--keep-workspace]
 *
 * Exit codes: 0 = the plugin activated, 1 = it did not, 2 = inconclusive.
 * The probe only reads and writes inside its own temporary DSH_HOME.
 */
import { spawnSync } from "node:child_process";
import { mkdirSync, mkdtempSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = resolve(fileURLToPath(new URL("..", import.meta.url)));
const argv = process.argv.slice(2);

function option(name, fallback) {
  const index = argv.indexOf(name);
  return index >= 0 && index + 1 < argv.length ? argv[index + 1] : fallback;
}

const dshBin = option("--dsh-bin", process.platform === "win32" ? "dsh.cmd" : "dsh");
const npmBin = process.platform === "win32" ? "npm.cmd" : "npm";
const timeoutSeconds = Number(option("--timeout", "60"));
const jsonOutput = argv.includes("--json");
const keepWorkspace = argv.includes("--keep-workspace");
const specArgument = option("--spec", undefined);

const PROFILE = "compat";
const FAILURE = /did not activate|failed to import|plugin tree failed to load|Cannot find module|ERR_MODULE_NOT_FOUND/i;
const ACTIVATED = /\[dsh-deeptutor\] plugin loaded/;

function run(command, args, options = {}) {
  return spawnSync(command, args, {
    encoding: "utf8",
    timeout: (options.timeoutSeconds ?? 180) * 1000,
    killSignal: "SIGKILL",
    input: "",
    cwd: options.cwd ?? repoRoot,
    env: { ...process.env, ...(options.env ?? {}) },
  });
}

function tail(text, lines = 25) {
  return String(text ?? "")
    .trimEnd()
    .split("\n")
    .slice(-lines)
    .join("\n");
}

/** The model/patch layer the boot probe needs: a real model name behind a dead port. */
function writeProbePatch(profileDir) {
  mkdirSync(profileDir, { recursive: true });
  writeFileSync(
    join(profileDir, "cordis.patch.yml"),
    [
      "# generated by scripts/check-dsh-compat.mjs — real model name behind a dead endpoint",
      "- id: llm-compat",
      "  config:",
      "    models:",
      "      - id: Qwen3.6-35B",
      "        contextWindow: 262144",
      "        maxTokens: 8192",
      "- id: agent-default-model",
      "  config:",
      "    provider: deepseek-official",
      "    model: Qwen3.6-35B",
      "- id: \"@deepseek-ai/cordis-plugin-hmr\"",
      "  disabled: true",
      "",
    ].join("\n"),
  );
}

function main() {
  const dshVersionProbe = run(dshBin, ["--version"], { timeoutSeconds: 30 });
  if (dshVersionProbe.error !== undefined || dshVersionProbe.status !== 0) {
    return {
      verdict: "inconclusive",
      stage: "dsh-version",
      detail: `${dshBin} is not runnable: ${String(dshVersionProbe.error ?? dshVersionProbe.stderr)}`.trim(),
      exitCode: 2,
    };
  }
  const dshVersion = String(dshVersionProbe.stdout ?? "").trim().split("\n").pop() ?? "unknown";

  const workspace = mkdtempSync(join(tmpdir(), "dsh-compat-"));
  const dshHome = join(workspace, ".dsh");
  const env = { DSH_HOME: dshHome };
  const cleanup = () => {
    if (!keepWorkspace) rmSync(workspace, { recursive: true, force: true });
  };

  try {
    let spec = specArgument;
    if (spec === undefined) {
      // --cache: keep npm state inside the probe workspace, so a read-only or
      // root-owned npm cache on the caller's machine cannot fail the probe.
      const packed = run(npmBin, ["pack", "--pack-destination", workspace, "--cache", join(workspace, "npm-cache")], { timeoutSeconds: 300 });
      if (packed.status !== 0) {
        return { verdict: "inconclusive", stage: "pack", detail: tail(`${packed.stdout}\n${packed.stderr}`), exitCode: 2 };
      }
      const tarball = readdirSync(workspace).find((name) => name.endsWith(".tgz"));
      if (tarball === undefined) {
        return { verdict: "inconclusive", stage: "pack", detail: "npm pack produced no tarball", exitCode: 2 };
      }
      spec = join(workspace, tarball);
    }

    writeProbePatch(join(dshHome, "profiles", PROFILE));

    // `-w`: dsh profiles are single-package pnpm workspaces and pnpm refuses
    // to add to a workspace root without it (observed on pnpm 9 + dsh 0.2.1).
    // Isolated pnpm store: a machine-wide store (store-dir in ~/.npmrc) can be
    // read-only for this user, which would look like an install failure.
    const install = run(
      dshBin,
      ["plugin", "--profile", PROFILE, "add", "-w", `--store-dir=${join(workspace, "pnpm-store")}`, spec],
      { timeoutSeconds: 300, env },
    );
    if (install.status !== 0) {
      return {
        verdict: "fail",
        stage: "install",
        detail: tail(`${install.stdout}\n${install.stderr}`),
        exitCode: 1,
      };
    }

    const boot = run(dshBin, ["--profile", PROFILE, "ok"], {
      timeoutSeconds,
      env: {
        ...env,
        DEEPSEEK_BASE_URL: "http://127.0.0.1:9",
        DEEPSEEK_API_KEY: "sk-compat-probe-000000000000000000000000",
        DSH_PERMISSION_MODE: "danger-full-access",
      },
      cwd: dshHome,
    });
    const log = `${boot.stdout ?? ""}\n${boot.stderr ?? ""}`;
    const timedOut = boot.error?.code === "ETIMEDOUT";
    const failure = log.match(FAILURE);
    if (failure !== null) {
      return { verdict: "fail", stage: "boot", detail: tail(log), signature: failure[0], exitCode: 1 };
    }
    if (log.match(ACTIVATED) !== null) {
      return { verdict: "pass", stage: "boot", detail: "plugin activation marker seen", exitCode: 0 };
    }
    if (timedOut) {
      return { verdict: "pass", stage: "boot", detail: "boot stayed alive through the probe window without a failure signature", exitCode: 0 };
    }
    return { verdict: "inconclusive", stage: "boot", detail: tail(log), exitCode: 2 };
  } finally {
    cleanup();
  }
}

const result = main();
const versionProbe = run(dshBin, ["--version"], { timeoutSeconds: 30 });
const report = {
  dshBin,
  dshVersion: String(versionProbe.stdout ?? "").trim().split("\n").pop() ?? "unavailable",
  spec: specArgument ?? "(packed from the repository)",
  ...result,
};

if (jsonOutput) {
  process.stdout.write(`${JSON.stringify(report, null, 2)}\n`);
} else {
  const label = report.verdict === "pass" ? "PASS" : report.verdict === "fail" ? "FAIL" : "INCONCLUSIVE";
  process.stdout.write(`[dsh-compat] ${label} · dsh ${report.dshVersion} · stage ${report.stage}\n`);
  if (report.detail !== undefined && report.detail !== "") process.stdout.write(`${report.detail}\n`);
  if (keepWorkspace) process.stdout.write(`[dsh-compat] workspace kept\n`);
}
process.exit(report.exitCode);
